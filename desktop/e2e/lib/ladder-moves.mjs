// The ladder moves a test run's pages confirmed, as a learning source (spec docs/superpowers/specs/2026-10-12-one-next-move.md, phase 1): the CI pool and the recorded replays feed the
// same counts real use does (desktop/lib/ladder/learning.js counts(): {shape, rung, kind, outcome, hits, misses}, fixed values and integers only), MARKED with their source so test data
// never poses as a user's. Counted by the app's own store functions on a scratch file, so a test run counts exactly as an install would. Two readers:
//  - movesFromLog(text): the app's own lines (a run with the real app: the pool's live row, a row case): `ladder: confirmed by rung N`, `ladder: learned by rung N`,
//    `ladder: learned answer confirmed`, `ladder: learned answer dropped (one miss)`, `page kind forgotten: ...` (desktop/lib/server-pages.js decidePageKind);
//  - movesFromRequests(requests): the extension's bodies to a stand-in app (a page case: lib/real-extension.mjs), shaped by the app's own key (rung1-kept.js kindKey).
// sendMoves(rows, {source}): ONE POST to the site's learning batch (POST /api/controls, `ladder` + `source`: site/src/ladder-moves.js), Bearer REPLAYS_PUBLISH_KEY (CI's narrow key);
// CI only, never a control run on an old build; JP_MOVES_DRY=1|true: say it, send nothing. Guard: e2e/test/ladder-moves.test.mjs.
import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

// The learning store imports desktop/shared/ (generated by scripts/stage.mjs, gitignored): a job that never staged it (the recorded pages' shards, a pool run where no row ran) stages it here, once.
const DESKTOP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
if (!fs.existsSync(path.join(DESKTOP, 'shared', 'alias-schema.js'))) execFileSync(process.execPath, [path.join(DESKTOP, 'scripts', 'stage.mjs'), '--files-only'], {cwd: DESKTOP, stdio: 'ignore'});
const {confirm, counts, hit, ladderStore, miss, record} = await import('../../lib/ladder/learning.js');
const {kindKey} = await import('../../lib/ladder/rung1-kept.js');

export const MOVES_SITE = 'https://www.jobpilotto.top/api/controls';
export const SOURCES = ['ci', 'replay'];   // the site's test sources (site/src/ladder-moves.js); 'user' is an install's own batch, never sent from here
const scratch = () => ladderStore(path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'jp-moves-')), 'ladder-learning.json'));
const verified = {signal: 'confident', verified: true};
// One event on the scratch store, through the app's own rules (a value outside the fixed lists, a shape with a query or text: nothing counted).
const take = (store, {event, shape, rung, kind, outcome}) => {
  if (event === 'verified') return rung < 3 ? confirm(store, shape, {rung, kind, outcome, ...verified}) : record(store, shape, {rung, kind, outcome, ...verified});
  if (event === 'hit') return hit(store, shape);
  if (event === 'miss') return miss(store, shape);
  return false;
};
const rowsOf = events => { const store = scratch(); for (const one of events) take(store, one); return counts(store); };

const LINE = /^\S+ \[extension\] (ladder: confirmed by rung (\d)|ladder: learned by rung (\d)|ladder: learned answer confirmed|ladder: learned answer dropped \(one miss\)|page kind forgotten:[^{]*?) (\{.*\})$/;
export function movesFromLog(text) {
  const events = [];
  for (const raw of String(text || '').split('\n')) {
    const found = raw.match(LINE);
    if (!found) continue;
    let data = null;
    try { data = JSON.parse(found[4]); } catch { continue; }
    const rung = Number(found[2] ?? found[3]), shape = String(data?.shape || '');
    if (found[2] || found[3]) events.push({event: 'verified', shape, rung, kind: data?.kind, outcome: data?.outcome});
    else events.push({event: found[1] === 'ladder: learned answer confirmed' ? 'hit' : 'miss', shape});
  }
  return rowsOf(events);
}

export function movesFromRequests(requests) {
  const events = [];
  for (const request of Array.isArray(requests) ? requests : []) {
    if (request?.route !== '/extension/page-kind') continue;
    let body = null;
    try { body = JSON.parse(request.body); } catch { continue; }
    const shape = kindKey({url: body?.url, controls: body?.controls});
    if (body?.verified === true) events.push({event: 'verified', shape, rung: body.rung, kind: body.kind, outcome: body.outcome});
    else if (body?.confirmed === true) events.push({event: 'hit', shape});
    else if (body?.forget === true || body?.signal === 'contradicted') events.push({event: 'miss', shape});
  }
  return rowsOf(events);
}

// The kept-repair evidence of a run, {fp, verb, ok, failed} per control fingerprint and verb (the site's `repairs`, site/src/repair-evidence.js): from the app's own lines
// `[extension] fill: <verb> on control <n> {"worked":true,"fp":"..."}` (a run with the real app: the pool), or from the extension's bodies to a stand-in app
// (`/extension/account-judge` phase `repair-result`, the replays). Fixed values only: a fingerprint, a verb of the fill_repair list, two counts.
const REPAIR_LINE = /^\S+ \[extension\] fill: ([a-z_]{2,24}) on control \d+ (\{.*\})$/;
const tally = events => {
  const sum = new Map();
  for (const {fp, verb, ok} of events) {
    const row = cleanRepair({fp, verb, ok: 1, failed: 0}) && (sum.get(`${fp}\n${verb}`) || {fp, verb, ok: 0, failed: 0});
    if (!row) continue;
    row[ok ? 'ok' : 'failed'] += 1;
    sum.set(`${fp}\n${verb}`, row);
  }
  return [...sum.values()].sort((a, b) => (a.fp + a.verb < b.fp + b.verb ? -1 : 1));
};
export function repairsFromLog(text) {
  const events = [];
  for (const raw of String(text || '').split('\n')) {
    const found = raw.match(REPAIR_LINE);
    if (!found) continue;
    let data = null;
    try { data = JSON.parse(found[2]); } catch { continue; }
    if (typeof data?.worked === 'boolean') events.push({fp: String(data.fp || ''), verb: found[1], ok: data.worked});
  }
  return tally(events);
}
export function repairsFromRequests(requests) {
  const events = [];
  for (const request of Array.isArray(requests) ? requests : []) {
    if (request?.route !== '/extension/account-judge') continue;
    let body = null;
    try { body = JSON.parse(request.body); } catch { continue; }
    if (body?.phase !== 'repair-result') continue;
    for (const row of Array.isArray(body.results) ? body.results : []) events.push({fp: String(row?.fp || ''), verb: String(row?.verb || ''), ok: row?.ok === true});
  }
  return tally(events);
}

// The rows of several runs, added per shape and decision; sorted by shape, then rung.
export function mergeMoves(lists) {
  const sum = new Map();
  for (const row of (Array.isArray(lists) ? lists : []).flat()) {
    const key = [row.shape, row.rung, row.kind, row.outcome].join('\n'), was = sum.get(key);
    sum.set(key, was ? {...was, hits: was.hits + row.hits, misses: was.misses + row.misses} : {...row});
  }
  return [...sum.values()].sort((a, b) => (a.shape < b.shape ? -1 : a.shape > b.shape ? 1 : a.rung - b.rung));
}

// A CI pool run (desktop/e2e/record-sites.mjs's day report + each row's saved app log `<day>-<row>.app.log`): the moves per row that ran in THIS run, and how many rows that reached
// a form have a confirmed move (the phase-1 proof). readLog(name) -> the text, '' when missing. -> {rows: [{row, reached, moves}], formRows: {reached, withMove}, moves, lines}.
const FORM = new Set(['form', 'ready']);
const said = moves => moves.map(move => `rung ${move.rung} ${move.kind}→${move.outcome} ×${move.hits}${move.misses ? ` (${move.misses} missed)` : ''}`).join(', ') || '-';
export function poolMoves(report = {}, readLog = () => '') {
  const ran = Array.isArray(report.thisRun?.ran) ? report.thisRun.ran : Object.keys(report.results || {});
  const logs = new Map(ran.filter(row => report.results?.[row]).map(row => [row, String(readLog(`${report.day}-${row.replace(/\W+/g, '-')}.app.log`) || '')]));
  const rows = [...logs].map(([row, log]) => ({row, reached: String(report.results[row].reached || 'none'), moves: movesFromLog(log)}));
  const formRows = {reached: rows.filter(item => FORM.has(item.reached)).length, withMove: rows.filter(item => FORM.has(item.reached) && item.moves.length).length};
  const lines = ['| Row | Reached | Moves | Confirmed |', '|---|---|---|---|', ...rows.map(item => `| ${item.row} | ${item.reached} | ${item.moves.length} | ${said(item.moves)} |`),
    `ladder moves: rows that reached a form: ${formRows.reached}, with a confirmed move: ${formRows.withMove}`];
  return {rows, formRows, moves: mergeMoves(rows.map(item => item.moves)), repairs: repairsFromLog([...logs.values()].join('\n')), lines};
}

// The distinct moves of several lists (a replayed move counts once, as the site keeps it: one hit, the misses of none): the recorded cases of one build, several cases on one host.
export const distinctMoves = lists => mergeMoves([...new Map((Array.isArray(lists) ? lists : []).flat().map(row => [[row.shape, row.rung, row.kind, row.outcome].join('\n'), {...row, hits: 1, misses: 0}])).values()].map(row => [row]));

// The repairs of several cases, one per control fingerprint and verb (a replayed repair is one repair, as a replayed move is one move): worked in some case, failed in some case.
export const distinctRepairs = lists => {
  const sum = new Map();
  for (const row of (Array.isArray(lists) ? lists : []).flat()) {
    const key = `${row.fp}\n${row.verb}`, was = sum.get(key) || {fp: row.fp, verb: row.verb, ok: 0, failed: 0};
    sum.set(key, {...was, ok: was.ok || (row.ok > 0 ? 1 : 0), failed: was.failed || (row.failed > 0 ? 1 : 0)});
  }
  return [...sum.values()];
};

// The control level's kept repairs travel in the same batch (jobadabra-fill-ladder, 12 Oct 2026: one delivery path): {fp (page/skeleton.js control fingerprint), verb (a fill_repair
// verb), ok, failed}, fixed words and integers only; the site's handling of `repairs` is the fill ladder's.
export const cleanRepair = raw => (/^[a-z0-9]{6,16}$/.test(String(raw?.fp ?? '')) && /^[a-z_]{2,24}$/.test(String(raw?.verb ?? '')) && [raw?.ok, raw?.failed].every(n => Number.isInteger(n) && n >= 0 && n <= 1e6) && raw.ok + raw.failed > 0
  ? {fp: raw.fp, verb: raw.verb, ok: raw.ok, failed: raw.failed} : null);

// -> one line for the run's output; never throws.
export async function sendMoves(rows, {source, repairs = [], env = process.env, fetcher = fetch} = {}) {
  if (!SOURCES.includes(source)) return `ladder moves: not sent (source "${source}" is not a test source)`;
  const why = env.REAL_EXTENSION_DIR ? 'a control run on another build' : !env.CI ? 'a local run: only CI sends test moves' : !env.REPLAYS_PUBLISH_KEY ? 'REPLAYS_PUBLISH_KEY not set up' : '';
  if (why) return `ladder moves: not sent (${why})`;
  const fixes = (Array.isArray(repairs) ? repairs : []).map(cleanRepair).filter(Boolean).slice(0, 200);
  if (!rows.length && !fixes.length) return 'ladder moves: nothing to send (no move was confirmed)';
  if (['1', 'true'].includes(String(env.JP_MOVES_DRY || '').toLowerCase())) return `ladder moves: dry run: would send ${rows.length} move(s)${fixes.length ? ` and ${fixes.length} repair(s)` : ''} (${source})`;
  try {
    const answer = await fetcher(MOVES_SITE, {method: 'POST', headers: {Authorization: `Bearer ${env.REPLAYS_PUBLISH_KEY}`, 'Content-Type': 'application/json', 'X-Caller': 'ladder-moves'},
      body: JSON.stringify({install: `${source}-test-moves`, source, run: String(env.GITHUB_RUN_ID || ''), ladder: rows.slice(0, 200), ...(fixes.length ? {repairs: fixes} : {})}), signal: AbortSignal.timeout(20000)});
    const body = await answer.json().catch(() => ({}));
    return answer.ok ? `ladder moves: ${rows.length} move(s)${fixes.length ? ` and ${fixes.length} repair(s)` : ''} sent (${source}), ${body.ladder ?? 0} stored` : `ladder moves: refused (${answer.status} ${body.error || ''})`;
  } catch (error) { return `ladder moves: not sent (${String(error?.message || error).slice(0, 80)})`; }
}
